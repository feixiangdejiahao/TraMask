"""Python probe materialization, independent of selection and evaluation labels.

Only statements at AST source boundaries can be instrumented. Expressions are
lowered to read paths, never eval'ed. Runtime attribute reads are static and
custom descriptors/subscripts are unknown. Alias labels are exact per snapshot,
not persistent object IDs, so instrumentation does not retain subject objects.
"""
from __future__ import annotations

import ast
import hashlib
import json
import math


HELPER_PATH = "__relation_runtime.py"
HELPER_SOURCE = r'''"""Injected read-only relation probes; generated by relation_search.runtime."""
import inspect
from itertools import islice
import json
import math
import os
from pathlib import Path

_MISSING = object()


def _lookup(spec, local, global_):
    if spec.get("kind") == "literal":
        return spec["value"]
    name = spec["root"]
    value = local[name] if name in local else global_.get(name, _MISSING)
    if value is _MISSING:
        raise LookupError("unbound_name")
    for step in spec["steps"]:
        if "attribute" in step:
            value = inspect.getattr_static(value, step["attribute"], _MISSING)
            if value is _MISSING:
                raise LookupError("missing_attribute")
            # Accessing a descriptor could execute arbitrary subject code.
            if inspect.getattr_static(type(value), "__get__", _MISSING) is not _MISSING:
                raise TypeError("descriptor_not_read")
        else:
            key = step["key"]
            if type(value) is dict:
                # Avoid __eq__ on arbitrary user key objects with colliding hashes.
                value = next((v for k, v in value.items()
                              if type(k) is type(key) and k == key), _MISSING)
                if value is _MISSING:
                    raise LookupError("missing_key")
            elif type(value) in (list, tuple) and type(key) is int:
                value = value[key]
            else:
                raise TypeError("custom_subscript_not_read")
    return value


def _encode(value, aliases, seen, depth=0):
    kind = type(value)
    if value is None or kind in (bool, int):
        return {"type": kind.__name__, "value": value}
    if kind is float:
        return {"type": "float", "value": value if math.isfinite(value) else str(value)}
    if kind is str:
        return {"type": "str", "value": value[:2048], "truncated": len(value) > 2048}
    if kind is bytes:
        return {"type": "bytes", "hex": value[:512].hex(), "truncated": len(value) > 512}
    identity = id(value)
    alias = aliases.setdefault(identity, len(aliases))
    result = {"type": type.__getattribute__(kind, "__name__"), "alias": alias}
    if identity in seen:
        result["reference"] = True
        return result
    seen.add(identity)
    if depth >= 3:
        result["truncated"] = True
    elif kind in (list, tuple):
        result["items"] = [_encode(item, aliases, seen, depth + 1) for item in value[:32]]
        result["length"] = len(value)
        result["truncated"] = len(value) > 32
    elif kind is dict:
        result["items"] = [[_encode(k, aliases, seen, depth + 1),
                            _encode(v, aliases, seen, depth + 1)]
                           for k, v in islice(value.items(), 32)]
        result["length"] = len(value)
        result["truncated"] = len(value) > 32
    else:
        # No repr, descriptor access, iteration, equality, or user methods.
        result["opaque"] = True
    return result


def capture(candidate_id, source_window, probe_id, phase, roles, local, global_):
    """Logging/unsupported values must not change whether the test executes."""
    try:
        aliases, seen, values, partition = {}, set(), [], {}
        for role in roles:
            row = {"name": role["name"], "expression": role["expression"],
                   "origin_span": role.get("origin_span"),
                   "kind": role["read_path"]["kind"]}
            try:
                value = _lookup(role["read_path"], local, global_)
                row["status"] = "observed"
                row["value"] = _encode(value, aliases, seen)
                if row["kind"] != "literal" and "alias" in row["value"]:
                    partition.setdefault(str(row["value"]["alias"]), []).append(role["name"])
            except Exception as error:
                row.update(status="unknown", reason=type(error).__name__)
            values.append(row)
        row = {"candidate_id": candidate_id, "source_window": source_window,
               "probe_id": probe_id, "phase": phase, "roles": values,
               "alias_scope": "this_snapshot_only", "alias_partition": list(partition.values())}
        directory = os.environ.get("COMBINATION_REPORT_DIR")
        if directory:
            destination = Path(directory) / "relation_trace.jsonl"
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
    except Exception:
        pass
'''


def _read_path(expression):
    """Compile a deliberately small pure-read syntax into data, not Python code."""
    node = ast.parse(expression, mode="eval").body
    def closed(value):
        if value is None or type(value) in (str, bool, int):
            return True
        if type(value) is float:
            return math.isfinite(value)
        if type(value) is list:
            return all(closed(item) for item in value)
        if type(value) is dict:
            return all(type(k) in (str, int) and closed(v) for k, v in value.items())
        return False
    try:
        value = ast.literal_eval(node)
    except (ValueError, TypeError, SyntaxError):
        pass
    else:
        if not closed(value):
            raise ValueError("literal probes support finite scalar/closed list/dict values")
        return {"kind": "literal", "value": value}
    steps = []
    while not isinstance(node, ast.Name):
        if isinstance(node, ast.Attribute):
            steps.append({"attribute": node.attr})
            node = node.value
        elif isinstance(node, ast.Subscript):
            try:
                key = ast.literal_eval(node.slice)
            except (ValueError, TypeError, SyntaxError):
                raise ValueError("probe subscripts require literal string/int keys") from None
            if type(key) not in (str, int):
                raise ValueError("probe subscripts require literal string/int keys")
            steps.append({"key": key})
            node = node.value
        else:
            raise ValueError("probe expression must be Name/Attribute/Subscript pure-read syntax")
    return {"kind": "read", "root": node.id, "steps": list(reversed(steps))}


def prepare_python_probes(source, path, candidate_id, source_window, runtime_probes):
    """Return generic-emitter byte edits and one separately mounted helper file.

    Input probes: {phase, insert_before: {path,start_byte,end_byte}, roles:
    [{name, expression, origin_span}], optional probe_id}. Positions refer to
    unmodified source, exactly as other generic emitter edits do. Multiple
    probes at one statement are merged into one insertion edit.
    """
    data = source.encode("utf-8")
    lines = data.splitlines(keepends=True)
    starts, offset = [], 0
    for line in lines:
        starts.append(offset)
        offset += len(line)
    boundaries = {starts[node.lineno - 1] + node.col_offset
                  for node in ast.walk(ast.parse(source)) if isinstance(node, ast.stmt)}
    groups = {}
    metadata = []
    for probe in runtime_probes:
        span = probe["insert_before"]
        if span.get("path", path) != path or span["start_byte"] not in boundaries:
            raise ValueError("probe insertion must match an AST statement boundary in the same source")
        position = span["start_byte"]
        line_start = data.rfind(b"\n", 0, position) + 1
        indent = data[line_start:position].decode()
        if indent.strip():
            raise ValueError("single-line compound statements are unsupported probe sites")
        roles = []
        for role in probe["roles"]:
            roles.append({"name": role["name"], "expression": role["expression"],
                          "origin_span": role.get("origin_span"),
                          "read_path": _read_path(role["expression"])})
        if len({role["name"] for role in roles}) != len(roles):
            raise ValueError("role names must be unique within a probe")
        identifier = probe.get("probe_id") or hashlib.sha256(
            json.dumps([probe["phase"], span, roles], sort_keys=True).encode()).hexdigest()[:16]
        binding = "__relation_probe_" + hashlib.sha256(str(candidate_id).encode()).hexdigest()[:12]
        payload = repr((candidate_id, source_window, identifier, probe["phase"], roles))
        code = ("try:\n" + indent + "    import __relation_runtime as " + binding + "\n"
                + indent + "    " + binding + ".capture(*" + payload + ", locals(), globals())\n"
                + indent + "except Exception:\n" + indent + "    pass\n" + indent)
        groups.setdefault(position, []).append(code)
        metadata.append({"probe_id": identifier, "phase": probe["phase"], "roles": roles,
                         "insert_before": span})
    edits = [{"span": {"path": path, "start_byte": position, "end_byte": position},
              "before": "", "after": "".join(codes)}
             for position, codes in sorted(groups.items())]
    return {"edits": edits, "helper_files": [{"path": HELPER_PATH, "code": HELPER_SOURCE}],
            "probes": metadata, "alias_scope": "per_snapshot",
            "unsupported": "calls, computed keys, descriptors, custom containers, inline suites"}
